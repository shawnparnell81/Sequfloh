using System.Net;
using ClosedXML.Excel;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using Sequfloh.Domain.Security;
using Sequfloh.Domain.Execution;
using Sequfloh.Infrastructure.Persistence;

namespace Sequfloh.Tests;

[Collection("api")]
public sealed class SequflohReportTests(TestApp app)
{
    const string S = "/api/sequfloh";
    static readonly string[] Planner = [Permissions.SequflohAccess, Permissions.SequflohViewLiveExecution, Permissions.SequflohCreateProductionTask, Permissions.SequflohDispatchTask,
        Permissions.SequflohViewReports, Permissions.SequflohExportRecords, Permissions.SequflohViewAuditTrail];

    async Task<(Guid Id, string Number)> ReleasedAsync(Guid site)
    {
        using var scope = app.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        var wi = new SequflohWorkInstruction { Type = WorkInstructionType.Validation, Title = "Housing check", Number = "RWI-" + Guid.NewGuid().ToString("N")[..8], Revision = "A", SiteId = site,
            Status = WorkInstructionStatus.Released, Steps = """[{"id":"x","sequence":10,"title":"Inspect housing"}]""", Characteristics = "[]", PartsRows = "[]", Content = "{}" };
        wi.FamilyId = wi.Id;
        db.SequflohWorkInstructions.Add(wi);
        await db.SaveChangesAsync();
        return (wi.Id, wi.Number);
    }

    [Fact]
    public async Task Reports_export_the_full_filtered_result_with_a_title_block_and_the_export_is_audited()
    {
        var site = await app.CreateSiteAsync();
        var (_, planner) = await app.CreateUserAsync(Planner, site);
        var (techId, _) = await app.CreateUserAsync([Permissions.SequflohAccess, Permissions.SequflohViewLiveExecution, Permissions.SequflohStartTask], site);
        var (_, viewer) = await app.CreateUserAsync([Permissions.SequflohAccess, Permissions.SequflohViewReports], site);
        var (_, plain) = await app.CreateUserAsync([Permissions.SequflohAccess], site);
        var wi = await ReleasedAsync(site);
        var tag = "WO-" + Guid.NewGuid().ToString("N")[..6];
        var numbers = new List<string>();
        for (var i = 0; i < 3; i++)
            numbers.Add((await (await planner.PostOkAsync($"{S}/tracking", new { type = "Production", workInstructionId = wi.Id, siteId = site, assignedUserId = techId, workOrder = tag, operation = "Assemble" })).JsonAsync()).Str("number"));

        Assert.Equal(HttpStatusCode.Forbidden, (await plain.GetAsync($"{S}/reports")).StatusCode);
        var cat = await viewer.GetElAsync($"{S}/reports");
        Assert.False(cat.GetProperty("canExport").GetBoolean());
        Assert.DoesNotContain(cat.GetProperty("reports").EnumerateArray(), r => r.Str("key") == "user-activity"); // needs the audit trail permission
        Assert.Equal(HttpStatusCode.Forbidden, (await viewer.GetAsync($"{S}/reports/production/xlsx?q={tag}")).StatusCode);

        var run = await planner.GetElAsync($"{S}/reports/task-performance?q={tag}&pageSize=2");
        Assert.Equal(3, run.GetProperty("total").GetInt32());
        Assert.Equal(2, run.GetProperty("items").GetArrayLength());
        Assert.Equal(3, run.GetProperty("statusCounts").GetProperty("Assigned").GetInt32());

        var res = await planner.GetAsync($"{S}/reports/production/xlsx?q={tag}&fileName=line-3");
        Assert.Equal(HttpStatusCode.OK, res.StatusCode);
        Assert.Equal("line-3.xlsx", res.Content.Headers.ContentDisposition?.FileNameStar ?? res.Content.Headers.ContentDisposition?.FileName?.Trim('"'));
        using (var wb = new XLWorkbook(await res.Content.ReadAsStreamAsync()))
        {
            var ws = wb.Worksheets.First();
            Assert.Equal("Production Tracking", ws.Cell(1, 2).GetString());
            Assert.Equal("Generated by", ws.Cell(5, 1).GetString());
            Assert.Contains(tag, ws.Cell(6, 2).GetString()); // active filters
            var header = ws.Row(9);
            Assert.Equal("Task", header.Cell(1).GetString());
            Assert.Equal(3, Enumerable.Range(10, 5).Count(r => numbers.Contains(ws.Cell(r, 1).GetString())));
        }

        var exports = await planner.GetElAsync($"{S}/audit/exports?q=line-3.xlsx");
        Assert.Equal(1, exports.GetProperty("total").GetInt32());
        var entry = exports.GetProperty("items")[0];
        Assert.Equal("Exported", entry.Str("action"));
        var detail = await planner.GetElAsync($"{S}/audit/entry/{entry.GetProperty("id").GetInt64()}");
        Assert.Contains("Production Tracking", detail.Str("description"));
        Assert.Equal(HttpStatusCode.NotFound, (await planner.GetAsync($"{S}/audit/everything")).StatusCode);
        Assert.Equal(HttpStatusCode.Forbidden, (await viewer.GetAsync($"{S}/audit/system")).StatusCode);
    }

    [Fact]
    public async Task Assignment_notifies_search_respects_site_and_prints_are_audited()
    {
        var site = await app.CreateSiteAsync();
        var other = await app.CreateSiteAsync();
        var (_, planner) = await app.CreateUserAsync(Planner, site);
        var (techId, tech) = await app.CreateUserAsync([Permissions.SequflohAccess, Permissions.SequflohViewLiveExecution, Permissions.SequflohStartTask], site);
        var (_, stranger) = await app.CreateUserAsync([Permissions.SequflohAccess], other);
        var wi = await ReleasedAsync(site);
        var rec = await (await planner.PostOkAsync($"{S}/tracking", new { type = "Production", workInstructionId = wi.Id, siteId = site, assignedUserId = techId, operation = "Final test" })).JsonAsync();
        var id = rec.Id(); var number = rec.Str("number");

        using (var scope = app.Services.CreateScope())
        {
            var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
            Assert.True(await db.Notifications.AnyAsync(n => n.UserId == techId && n.RecordId == id && n.Title.Contains("assigned to you")));
        }

        var found = await tech.GetElAsync($"{S}/search?q={number}");
        Assert.Contains(found.GetProperty("groups").EnumerateArray(), g => g.Str("key") == "tasks" && g.GetProperty("items").GetArrayLength() == 1);
        var hidden = await stranger.GetElAsync($"{S}/search?q={number}");
        Assert.All(hidden.GetProperty("groups").EnumerateArray(), g => Assert.Equal(0, g.GetProperty("items").GetArrayLength()));
        Assert.DoesNotContain(hidden.GetProperty("groups").EnumerateArray(), g => g.Str("key") == "users");
        var instr = await tech.GetElAsync($"{S}/search?q={wi.Number}");
        Assert.Contains(instr.GetProperty("groups").EnumerateArray(), g => g.Str("key") == "instructions" && g.GetProperty("items").GetArrayLength() == 1);

        var pdf = await tech.GetAsync($"{S}/tracking/{id}/print");
        Assert.Equal(HttpStatusCode.OK, pdf.StatusCode);
        Assert.Equal("application/pdf", pdf.Content.Headers.ContentType?.MediaType);
        Assert.Equal(HttpStatusCode.Forbidden, (await stranger.GetAsync($"{S}/tracking/{id}/print")).StatusCode);
        var summary = await planner.GetAsync($"{S}/audit/system/print?q={number}");
        Assert.Equal("application/pdf", summary.Content.Headers.ContentType?.MediaType);
        var printed = await planner.GetElAsync($"{S}/audit/exports?q={number}");
        Assert.Contains(printed.GetProperty("items").EnumerateArray(), a => a.Str("action") == "TrackingRecordPrinted");
    }
}
